#!/usr/bin/env python3
"""Unicode tables of selfhost/tilc.til.

The Python compiler classifies characters with str methods that use the
Unicode database of the Python running it: identifiers (`isalpha`,
`isalnum`), numbers (`isdigit`, and `int()` / `float()` accept the decimal
digits of every script) and the `repr()` of strings in E-CONTRACT messages
(`isprintable`). tilc carries the same information for the code points
>= 128 as two compact tables, generated by this script from `unicodedata`
and pasted into tilc.til between the markers

    # >>> unicode tables (generated ...)
    # <<< unicode tables

(White space, `str.isspace()`, is a short fixed list written out in
`ws_len` in tilc.til.)

Usage:
    python3 selfhost/unicode_tables.py           # print the block
    python3 selfhost/unicode_tables.py --write   # replace the block in tilc.til
    python3 selfhost/unicode_tables.py --check   # exit 1 if tilc.til is out of date

`--check` (and tests/test_selfhost.py) compares the block byte for byte when
this Python has the same Unicode version as the block. With an older Python
it checks that the tables agree with this Python for every code point that
is assigned here: newer Unicode versions only add characters (checked for
Python 3.9 / Unicode 13.0 to 3.13 / Unicode 15.1).

Encoding: every entry is a 24-bit number written as 4 characters of a
64-letter alphabet ('#' .. 'c' without the backslash), so that the tables are
plain string constants (no heap is needed to hold them).

* U_LEX: one entry per run of code points >= 128 with the same class,
  `start * 8 + class`; class 0 other, 1 letter (isalpha), 2 decimal digit
  (isdecimal), 3 other digit (isdigit), 4 other numeric (isalnum). Runs of
  decimal digits start with a zero digit, so the value of a digit is
  `(code point - start of its run) % 10` (asserted below).
* U_PRINT: the code points >= 128 where str.isprintable() changes (it is
  false for U+0080); a code point is printable when an odd number of entries
  is <= it.
"""

import bisect
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
TILC = os.path.join(HERE, 'tilc.til')
BEGIN = '# >>> unicode tables'
END = '# <<< unicode tables'
FIRST, LIMIT = 0x80, 0x110000


def char_class(ch: str) -> int:
    if ch.isalpha():
        return 1
    if ch.isdecimal():
        return 2
    if ch.isdigit():
        return 3
    if ch.isalnum():
        return 4
    return 0


def lexer_runs():
    runs, prev = [], None
    for cp in range(FIRST, LIMIT):
        k = char_class(chr(cp))
        if k != prev:
            runs.append((cp, k))
            prev = k
    return runs


def printable_bounds():
    assert not chr(FIRST).isprintable()
    bounds, prev = [], False
    for cp in range(FIRST, LIMIT):
        p = chr(cp).isprintable()
        if p != prev:
            bounds.append(cp)
            prev = p
    return bounds


def digit_char(v: int) -> str:
    c = 0x23 + v
    return chr(c + 1 if c >= 0x5C else c)


def char_digit(c: str) -> int:
    o = ord(c)
    return o - 0x23 - (1 if o > 0x5C else 0)


def encode(values) -> str:
    out = []
    for v in values:
        assert 0 <= v < 1 << 24
        out.append(''.join(digit_char((v >> s) & 63) for s in (18, 12, 6, 0)))
    return ''.join(out)


def decode(text: str):
    assert len(text) % 4 == 0
    vals = []
    for i in range(0, len(text), 4):
        v = 0
        for c in text[i:i + 4]:
            v = v * 64 + char_digit(c)
        vals.append(v)
    return vals


def til_string(name: str, text: str, width: int = 96) -> str:
    chunks = [text[i:i + width] for i in range(0, len(text), width)]
    lines = [f'let {name} = ("{chunks[0]}"']
    lines += [f'    + "{c}"' for c in chunks[1:]]
    lines[-1] += ')'
    return '\n'.join(lines)


def block() -> str:
    runs = lexer_runs()
    for i, (start, k) in enumerate(runs):
        if k == 2:   # tilc's udigit(): (cp - start of the run) % 10
            end = runs[i + 1][0] if i + 1 < len(runs) else LIMIT
            assert all(unicodedata.decimal(chr(cp)) == (cp - start) % 10 for cp in range(start, end)), hex(start)
    lex = encode(cp * 8 + k for cp, k in runs)
    prt = encode(printable_bounds())
    return '\n'.join([
        f'{BEGIN} (generated by selfhost/unicode_tables.py from Unicode '
        f'{unicodedata.unidata_version}; do not edit)',
        f'const UNICODE_VERSION = "{unicodedata.unidata_version}"',
        til_string('U_LEX', lex),
        til_string('U_PRINT', prt),
        END,
    ])


def block_span(source: str):
    a = source.index(BEGIN)
    return a, source.index(END, a) + len(END)


def read_block(source: str):
    """(unicode version, lexer runs [(start, class)], printable bounds) stored in tilc.til."""
    a, b = block_span(source)
    text = source[a:b]
    version = re.search(r'^const UNICODE_VERSION = "([^"]*)"$', text, re.M).group(1)

    def table(name):
        # `let NAME = ("..."` and `    + "..."` lines (the alphabet has no '"')
        m = re.search(r'^let ' + name + r' = \("[^"]*"\)?\n(?:    \+ "[^"]*"\)?\n)*', text, re.M)
        return ''.join(re.findall(r'"([^"]*)"', m.group(0)))
    lex = [(v >> 3, v & 7) for v in decode(table('U_LEX'))]
    return version, lex, decode(table('U_PRINT'))


def check(source: str):
    """Problems of the block in `source` against this Python (empty list: in sync)."""
    a, b = block_span(source)
    version, runs, bounds = read_block(source)
    if version == unicodedata.unidata_version:
        if source[a:b] != block():
            return [f"the Unicode {version} tables differ from this Python's; "
                    "run selfhost/unicode_tables.py --write"]
        return []
    # another Unicode version: the same answers for every character assigned here
    starts = [s for s, _ in runs]
    problems = []
    for cp in range(FIRST, LIMIT):
        ch = chr(cp)
        if unicodedata.category(ch) == 'Cn':
            continue
        run = bisect.bisect_right(starts, cp) - 1
        k = runs[run][1]
        printable = bisect.bisect_right(bounds, cp) % 2 == 1
        if k != char_class(ch) or printable != ch.isprintable() or (
                k == 2 and (cp - starts[run]) % 10 != unicodedata.decimal(ch)):
            problems.append(f"U+{cp:04X}: tilc.til (Unicode {version}) has class {k}, printable {printable}; "
                            f"Python (Unicode {unicodedata.unidata_version}) class {char_class(ch)}, "
                            f"printable {ch.isprintable()}")
    return problems


def main(argv) -> int:
    if not argv:
        print(block())
        return 0
    with open(TILC, encoding='utf-8') as f:
        source = f.read()
    if argv[0] == '--check':
        problems = check(source)
        for p in problems[:20]:
            print('selfhost/tilc.til: ' + p)
        return 1 if problems else 0
    if argv[0] == '--write':
        a, b = block_span(source)
        with open(TILC, 'w', encoding='utf-8', newline='\n') as f:
            f.write(source[:a] + block() + source[b:])
        return 0
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
